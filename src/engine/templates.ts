export const TEMPLATES: Record<string, DecisionTemplate> = {
  lunch_offer: LUNCH_OFFER,
  price_change: PRICE_CHANGE,
};

export function getTemplate(id: string): DecisionTemplate {
  const t = TEMPLATES[id];
  if (!t) throw new Error(`Unknown decision template "${id}". Available: ${Object.keys(TEMPLATES).join(", ")}`);
  return t;
}

export function demoInputs(id: string): Record<string, number | string> {
  return Object.fromEntries(getTemplate(id).fields.map((f) => [f.key, f.example]));
}
